#!/usr/bin/env python3
"""Render printable ASCII (32-126) from DejaVu Sans Mono into a 16x32 1-bit font -> font.h"""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
W, H = 16, 32
font = ImageFont.truetype(TTF, 26)
asc, desc = font.getmetrics()

rows = []
for c in range(32, 127):
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    x0, _, x1, _ = d.textbbox((0, 0), chr(c), font=font)
    d.text(((W - (x1 - x0)) // 2 - x0, (H - asc - desc) // 2), chr(c), fill=255, font=font)
    px = img.load()
    rows.append([sum(1 << (15 - x) for x in range(W) if px[x, y] > 110) for y in range(H)])

with open("font.h", "w") as f:
    f.write("// Generated by gen_font.py from DejaVu Sans Mono: ASCII 32-126, 16x32, 1 bit per pixel\n")
    f.write("#define FONT_W 16\n#define FONT_H 32\n")
    f.write("static const unsigned short font[95][32] = {\n")
    for c, r in zip(range(32, 127), rows):
        f.write("  {" + ",".join(f"0x{v:04x}" for v in r) + f"}}, // {chr(c)!r}\n")
    f.write("};\n")

# preview for checking
prev = Image.new("L", (W * 32, H * 3), 0)
for i, r in enumerate(rows):
    for y, v in enumerate(r):
        for x in range(W):
            if v & (1 << (15 - x)):
                prev.putpixel(((i % 32) * W + x, (i // 32) * H + y), 255)
prev.save("font-preview.png")
print("wrote font.h")
